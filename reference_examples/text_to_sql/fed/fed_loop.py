"""Federated harness evolution: broadcast -> parallel local evolution -> aggregate -> repeat.

One federated round:
  1. BROADCAST  the current global harness to every client
  2. LOCAL      each client runs optimize.py on its own shard, starting from that global (parallel)
  3. AGGREGATE  the merger folds the K client harnesses back into one global
  4. VERIFY     the merged global must load and still run; otherwise ROLL BACK to the broadcast global

After T rounds the global harness is frozen. Scoring it on a held-out set is a separate step
(fed/evaluate.py) — nothing in this loop reads gold.

Rollback goes to the PREVIOUS GLOBAL, not to the best client. Picking a "best" client would need
accuracy we do not have at training time (no gold), and it would break the invariant the merger
depends on: every client in a round starts from one shared broadcast harness.
"""
